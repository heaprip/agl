#!/usr/bin/env python3
"""Clean world of every binary relation on n elements (H72, docs/impl/clean.md).

Offline and deterministic: relation rK holds the pair (e_i, e_j) iff bit
i*n + j of K is set. Nothing is chosen; the names are labels only.

    python3 tools/clean_world.py 3 > cases/clean/all3.agl
"""
import sys

n = int(sys.argv[1]) if len(sys.argv) > 1 else 3
els = [f"e{i + 1}" for i in range(n)]
width = len(str(2 ** (n * n) - 1))
print(f"# Every binary relation on {n} elements: {2 ** (n * n)} relations, none chosen.")
print("# Generated by tools/clean_world.py; agl --explore grows the bank of each.")
print("world clean")
for k in range(2 ** (n * n)):
    name = f"r{k:0{width}d}"
    print(f"relation {name}(left, right)")
    for b in range(n * n):
        if k >> b & 1:
            i, j = divmod(b, n)
            print(f"fact {name}_{b}: {name}(left: {els[i]}, right: {els[j]}) @")
