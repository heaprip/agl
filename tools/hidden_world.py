#!/usr/bin/env python3
"""Clean world with a hidden magnitude (H73, docs/impl/scale.md).

Offline and deterministic. N objects get hidden weights; for a share of
pairs chosen by seed the world shows `heavier` (weights differ by more than
delta) or `alike` both ways (they do not). Weights stay in a comment for the
acceptance test; the kernel does not read comments. Names are shuffled so
that their order says nothing about the weights.

    python3 tools/hidden_world.py weights 14 1 2/3 > cases/clean/weights.agl
    python3 tools/hidden_world.py shuffled 14 1 2/3 > cases/clean/shuffled.agl
"""
import random
import sys
from fractions import Fraction

kind, n, seed, share = sys.argv[1], int(sys.argv[2]), int(sys.argv[3]), Fraction(sys.argv[4])
rng = random.Random(seed)
weights = sorted(rng.random() for _ in range(n))
# About three neighbours on each side cannot be told apart.
delta = 3.0 / n
names = [f"o{i + 1:02d}" for i in range(n)]
rng.shuffle(names)
pairs = [(i, j) for i in range(n) for j in range(i + 1, n)]
seen = [p for p in pairs if rng.random() < share]
verdicts = []
for i, j in seen:
    if weights[j] - weights[i] > delta:
        verdicts.append(("heavier", j, i))
    else:
        verdicts.append(("alike", i, j))
if kind == "shuffled":
    # Same counts of each verdict, laid on pairs at random: no hidden weight.
    kinds = [v[0] for v in verdicts]
    rng.shuffle(kinds)
    verdicts = []
    for k, (i, j) in zip(kinds, seen):
        a, b = (i, j) if rng.random() < 0.5 else (j, i)
        verdicts.append((k, a, b))
print(f"# Hidden magnitude world `{kind}`: {n} objects, seed {seed}, share {share} of pairs seen.")
print("# Generated by tools/hidden_world.py. The kernel sees only the facts.")
if kind == "weights":
    print("# hidden: " + " ".join(f"{names[i]}={weights[i]:.4f}" for i in range(n)))
    print(f"# hidden delta: {delta:.4f}")
print("world clean")
print("relation heavier(left, right)")
print("relation alike(left, right)")
facts = []
for k, a, b in verdicts:
    if k == "heavier":
        facts.append(f"heavier(left: {names[a]}, right: {names[b]})")
    else:
        facts.append(f"alike(left: {names[a]}, right: {names[b]})")
        facts.append(f"alike(left: {names[b]}, right: {names[a]})")
for i, f in enumerate(sorted(facts)):
    print(f"fact v{i}: {f} @")
